local function seed()
	local profile = Plater.db and Plater.db.profile
	if (not profile or not PlaterDB) then
		return
	end

	-- Imported retail profiles carry their NPC cache, colors and renames.
	-- Apply on every DB refresh so later imports cannot restore these entries.
	-- Use the same 3.3.5 creature-ID limit as the script-trigger cleanup.
	for _, key in ipairs({"npc_cache", "npc_colors", "npcs_renamed"}) do
		local entries = profile[key]
		if (type(entries) == "table") then
			for npcID in pairs(entries) do
				local id = tonumber(npcID)
				if (id and id > 40500) then
					entries[npcID] = nil
				end
			end
		end
	end

	if (profile.wotlk_seed_version ~= SEED_VERSION) then
		local npcCache = profile.npc_cache
		for npcID, info in pairs(NPCS) do
			if (not npcCache[npcID]) then
				npcCache[npcID] = {info[1], info[2], "enUS"}
			end
		end
		profile.wotlk_seed_version = SEED_VERSION
	end

	if (PlaterDB.wotlk_seed_version ~= SEED_VERSION) then
		PlaterDB.captured_casts = PlaterDB.captured_casts or {}
		PlaterDB.captured_spells = PlaterDB.captured_spells or {}
		local capturedCasts, capturedSpells = PlaterDB.captured_casts, PlaterDB.captured_spells
		for spellID, info in pairs(CASTS) do
			if (not capturedCasts[spellID]) then
				local npc = NPCS[info[2]]
				capturedCasts[spellID] = {event = info[1], source = npc and npc[1] or info[3], npcID = info[2], encounterName = info[3]}
			end
		end
		for spellID, info in pairs(SPELLS) do
			if (not capturedSpells[spellID]) then
				local npc = NPCS[info[2]]
				capturedSpells[spellID] = {event = info[1], source = npc and npc[1] or info[3], npcID = info[2], encounterName = info[3], type = info[1] == "SPELL_AURA_APPLIED" and "DEBUFF" or nil}
			end
		end
		PlaterDB.wotlk_seed_version = SEED_VERSION
	end
end

Plater.RegisterRefreshDBCallback(seed)
